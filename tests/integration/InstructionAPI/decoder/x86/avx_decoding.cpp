/*
 *  VEX, EVEX and AMX encodings that InstructionAPI did not decode.
 *
 *  Each encoding was assembled with GNU as 2.40; the comment is objdump 2.40's
 *  disassembly. The test checks that the bytes decode, to the expected length
 *  and mnemonic. Parsing stops at an instruction that does not decode, so a
 *  function that contains one is cut short and comes out as non-returning.
 *
 *  The mnemonic is InstructionAPI's, which differs from objdump's for
 *  vmovq (decoded as vmovd) and the vcmpph predicates.
 *
 *  The legacy SSE forms that share these opcodes are checked as well, and so
 *  are encodings that must stay undecodable.
 */

