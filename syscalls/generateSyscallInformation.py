import os
import sys
import string

def generate_dyn_syscalls(allSyscallNames):
    # Open file for writing
    outFile = open("dyn_syscalls.h", "w")

    # Write out "header" information
    outFile.write("/* This file was autogenerated from syscalls/generateSyscallInformation.py */" + "\n")
    outFile.write("#if !defined(DYN_SYSCALLS_H_)\n")
    outFile.write("#define DYN_SYSCALLS_H_ \n")
    outFile.write("\n")
    outFile.write("namespace Dyninst {\n")
    outFile.write("namespace Syscall {\n")
    outFile.write("enum {\n")

    # Write out our system calls!
    for syscall in allSyscallNames:
        if (syscall.find("//") == -1):
            outFile.write("\tdyn_" + syscall + ", \n")
        else:
            outFile.write("\t" + syscall + "\n")

    # Write out "footer" information
    outFile.write("};\n")
    outFile.write("}}\n")
    outFile.write("#endif\n")

    # Close file
    outFile.close()

def generate_SyscallInformation(allSyscallNames, allSyscalls):
    # Open file for writing
    outFile = open("SyscallInformation.C", "w")

    # Group the system calls by platform, keeping their order
    platforms = []
    for syscall in allSyscalls:
        platName = syscall[0] + "_" + syscall[1]
        if (len(platforms) == 0) or (platforms[-1][0] != platName):
            platforms.append((platName, syscall[0], syscall[1], []))
        platforms[-1][3].append(syscall)

    # Write out "header" information
    outFile.write("/* This file was autogenerated from syscalls/generateSyscallInformation.py */" + "\n")
    outFile.write("#include \"Architecture.h\"\n")
    outFile.write("#include \"dyn_syscalls.h\"\n")
    outFile.write("\n")
    outFile.write("#include <iterator>\n")
    outFile.write("#include <utility>\n")
    outFile.write("\n")
    outFile.write("namespace {\n")
    outFile.write("\n")
    outFile.write("// A system call's platform-independent ID, its number on one platform,\n")
    outFile.write("// and its name.  The tables of them are constant data, so they cost no\n")
    outFile.write("// code or stack to build; SyscallInformation's maps are filled from them.\n")
    outFile.write("struct SyscallEntry {\n")
    outFile.write("  MachSyscall::SyscallIDIndependent id;\n")
    outFile.write("  MachSyscall::SyscallIDPlatform number;\n")
    outFile.write("  MachSyscall::SyscallName name;\n")
    outFile.write("};\n")

    # Write out one table per platform
    for platName, curOS, curArch, syscalls in platforms:
        outFile.write("\n/* " + curOS + " " + curArch + " Numbers */\n")
        outFile.write("const SyscallEntry " + platName + "_syscalls[] = {\n")
        for syscall in syscalls:
            outFile.write("  {Syscall::dyn_" + syscall[2] + ", " + str(syscall[3]) + ", \"" + syscall[2] + "\"},\n")
        outFile.write("};\n")

    outFile.write("\n")
    outFile.write("}\n")
    outFile.write("\n")

    # Write out the constructor that fills the maps from the tables
    outFile.write("SyscallInformation::SyscallInformation()\n")
    outFile.write("{\n")
    outFile.write("  auto add = [](const SyscallEntry *first, const SyscallEntry *last,\n")
    outFile.write("                syscallNumbersMap &numbers, syscallNamesMap &names)  {\n")
    outFile.write("    for (; first != last; ++first)  {\n")
    outFile.write("      numbers.insert(std::make_pair(first->id, first->number));\n")
    outFile.write("      names.insert(std::make_pair(first->number, first->name));\n")
    outFile.write("    }\n")
    outFile.write("  };\n")
    for platName, curOS, curArch, syscalls in platforms:
        outFile.write("\n")
        outFile.write("  add(std::begin(" + platName + "_syscalls), std::end(" + platName + "_syscalls),\n")
        outFile.write("      " + platName + "_syscallNumbers, " + platName + "_syscallNames);\n")

    # Write out "footer" information
    outFile.write("}\n")

    # Close file
    outFile.close()

allSyscallNames = []
allSyscalls = []

