// Bits [valueLo, valueLo+width) of the field value go to instruction bits
// [loBit, loBit+width). A field split over several ranges has one entry per
// range. padBits > 0 means the value's low padBits bits are implied (equal to
// padValue) and are not stored, e.g. SBASE takes the SGPR number of an
// aligned pair and stores it shifted right by one.
struct FieldSpec {
  Field field;
  uint8_t loBit;
  uint8_t width;
  uint8_t valueLo;
  uint8_t padBits;
  uint8_t padValue;
};

